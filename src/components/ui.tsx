export function Alert({ tone = "blue", title, children }: { tone?: "blue" | "yellow" | "red" | "green"; title?: ReactNode; children?: ReactNode }) {
  const t = { blue: "border-blue-200 bg-blue-50 text-blue-900", yellow: "border-amber-200 bg-amber-50 text-amber-900", red: "border-red-200 bg-red-50 text-red-900", green: "border-emerald-200 bg-emerald-50 text-emerald-900" }[tone];
  return (
    <div className={clsx("rounded-lg border px-4 py-3 text-sm", t)}>
      {title && <p className="font-medium">{title}</p>}
      {children && <div className={clsx(title && "mt-0.5")}>{children}</div>}
    </div>
  );
}

/** Shows the ?ok= / ?err= message set by a form action redirect. */
export function Flash({ ok, err }: { ok?: string | string[]; err?: string | string[] }) {
  const o = Array.isArray(ok) ? ok[0] : ok;
  const e = Array.isArray(err) ? err[0] : err;
  if (!o && !e) return null;
  return <div className="mb-4">{e ? <Alert tone="red">{e}</Alert> : <Alert tone="green">{o}</Alert>}</div>;
}

export function Tabs({ items, current }: { items: { href: string; label: string; key: string; count?: number }[]; current: string }) {
  return (
    <nav className="mb-5 flex flex-wrap gap-1 border-b border-slate-200">
      {items.map((t) => (
        <Link key={t.key} href={t.href} className={clsx("-mb-px border-b-2 px-3 py-2 text-sm font-medium", t.key === current ? "border-blue-700 text-blue-800" : "border-transparent text-slate-500 hover:text-slate-800")}>
          {t.label}
          {t.count ? <span className="ml-1.5 rounded-full bg-slate-100 px-1.5 text-xs text-slate-600">{t.count}</span> : null}
        </Link>
      ))}
    </nav>
  );
}

export function formatDate(d: Date | string | null | undefined, opts: Intl.DateTimeFormatOptions = { dateStyle: "medium" }, tz?: string) {
  if (!d) return "—";
  const date = typeof d === "string" ? new Date(d) : d;
  if (Number.isNaN(date.getTime())) return "—";
  return new Intl.DateTimeFormat("en-US", { ...opts, timeZone: tz }).format(date);
}

export function formatDateTime(d: Date | string | null | undefined, tz?: string) {
  return formatDate(d, { dateStyle: "medium", timeStyle: "short" }, tz);
}

export function Stars({ rating }: { rating: number }) {
  return (
    <span className="text-amber-500" aria-label={`${rating} out of 5 stars`}>
      {"★".repeat(rating)}
      <span className="text-slate-300">{"★".repeat(Math.max(0, 5 - rating))}</span>
    </span>
  );
}
